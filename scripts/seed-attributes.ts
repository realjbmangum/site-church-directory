/**
 * Build church_attributes.sql from the research CSVs and load it into local D1.
 * Refuses --remote. Brian loads the remote database only after approving the pull request.
 * Pass --sql-only to regenerate the SQL file without touching a database.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseCsv } from '../shared/csv.ts';
import { slugify } from '../shared/slug.ts';
import { sqlString } from './directory.ts';

if (process.argv.includes('--remote')) {
  console.error('Refusing to load church attributes into the remote D1 database.');
  process.exit(1);
}

const root = join(import.meta.dirname, '..');
const filters = parseCsv(readFileSync(join(root, 'data/charlotte/church_filters.csv'), 'utf8'));
const mapping = parseCsv(readFileSync(join(root, 'data/charlotte/church_type_mapping.csv'), 'utf8'));

function clean(value: string | undefined): string | null {
  const text = (value ?? '').trim();
  if (!text || text.toLowerCase() === 'unknown') return null;
  return text;
}

const columns = [
  'church_id',
  'church_type',
  'specific_body',
  'nursery',
  'nursery_proof',
  'nursery_url',
  'kids_ministry',
  'kids_ministry_proof',
  'kids_ministry_url',
  'youth_group',
  'youth_group_proof',
  'youth_group_url',
  'worship_style',
  'worship_style_proof',
  'worship_style_url',
  'choir',
  'choir_proof',
  'choir_url',
  'young_adults',
  'young_adults_proof',
  'young_adults_url',
  'college_ministry',
  'college_ministry_proof',
  'college_ministry_url',
  'outreach',
  'outreach_proof',
  'outreach_url',
  'livestream_online',
  'livestream_online_proof',
  'livestream_online_url',
  'accessibility',
  'accessibility_proof',
  'accessibility_url',
  'small_groups_bible_study',
  'small_groups_bible_study_proof',
  'small_groups_bible_study_url',
  'school_preschool',
  'school_preschool_proof',
  'school_preschool_url',
  'beliefs_url',
  'lgbtq_stance',
  'lgbtq_stance_proof',
  'lgbtq_stance_url',
] as const;

const lines = [
  '-- Generated by scripts/seed-attributes.ts from data/charlotte/church_filters.csv.',
  '-- church_type and specific_body follow data/charlotte/church_type_mapping.csv.',
  '-- Keyed by churches.id. Unknown and blank values are stored as NULL, which means not found, never no.',
  '-- Apply locally only. Do not run this file against the remote D1 database until Brian approves it.',
  'DELETE FROM church_attributes;',
];

for (const row of filters) {
  const values = columns.map((column) => {
    if (column === 'church_id') return sqlString(row.id);
    if (column === 'church_type') return sqlString(clean(row.church_type));
    if (column === 'specific_body') return sqlString(clean(row.specific_body));
    if (column === 'beliefs_url') return sqlString(clean(row.beliefs_url));
    return sqlString(clean(row[column]));
  });
  lines.push(`INSERT INTO church_attributes (${columns.join(', ')}) VALUES (${values.join(', ')});`);
}

const sqlPath = join(root, 'data/charlotte/church_attributes.sql');
writeFileSync(sqlPath, `${lines.join('\n')}\n`);

const order: string[] = [];
const byKey: Record<string, string> = {};
const familyScore = new Map<string, { type: string; count: number }>();
for (const row of mapping) {
  const type = row['church_type (show on site)']?.trim();
  const family = row.current_family?.trim();
  const body = row['specific_body (secondary detail)']?.trim();
  if (!type) continue;
  if (!order.includes(type)) order.push(type);
  if (family) byKey[`${family}||${body || ''}`] = type;
  const count = Number(row.charlotte_churches_now || 0);
  const current = family ? familyScore.get(family) : undefined;
  if (family && (!current || count > current.count)) familyScore.set(family, { type, count });
}
const familyDefault: Record<string, string> = {};
for (const [family, winner] of familyScore) familyDefault[family] = winner.type;

const dataPath = join(root, 'shared/church-type-data.ts');
writeFileSync(
  dataPath,
  `// Generated by scripts/seed-attributes.ts from church_type_mapping.csv. Do not edit by hand.\nexport const CHURCH_TYPE_ORDER = ${JSON.stringify(order, null, 2)} as const;\n\nexport const TYPE_BY_FAMILY_BODY: Record<string, string> = ${JSON.stringify(byKey, null, 2)};\n\nexport const FAMILY_DEFAULT: Record<string, string> = ${JSON.stringify(familyDefault, null, 2)};\n`,
);

console.log(`Wrote ${filters.length} attribute rows to ${sqlPath}`);

if (process.argv.includes('--sql-only')) process.exit(0);

execFileSync(
  'npx',
  ['wrangler', 'd1', 'execute', 'church-directory', '--local', '--persist-to', '.wrangler/state', '--file', sqlPath],
  { cwd: root, stdio: 'inherit' },
);
